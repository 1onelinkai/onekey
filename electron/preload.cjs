  getAppInfo: () => ipcRenderer.invoke("onelink:app-info"),
  softwareUpdateStatus: () => ipcRenderer.invoke("onelink:software-update-status"),
  checkSoftwareUpdate: () => ipcRenderer.invoke("onelink:software-update-check"),
  authStatus: () => ipcRenderer.invoke("onelink:auth-status"),
  login: () => ipcRenderer.invoke("onelink:login"),
  logout: () => ipcRenderer.invoke("onelink:logout"),
  organizations: () => ipcRenderer.invoke("onelink:organizations"),
  detect: () => ipcRenderer.invoke("onelink:detect"),
  launchAgent: client => ipcRenderer.invoke("onelink:launch-agent", client),
  inspectConfig: client => ipcRenderer.invoke("onelink:inspect-config", client),
  installPlan: (client) => ipcRenderer.invoke("onelink:install-plan", client),
  install: (client) => ipcRenderer.invoke("onelink:install", client),
  installStatus: () => ipcRenderer.invoke("onelink:install-status"),
  checkUpdates: client => ipcRenderer.invoke("onelink:check-updates", client),
  updatePlan: client => ipcRenderer.invoke("onelink:update-plan", client),
  upgradeAgent: client => ipcRenderer.invoke("onelink:upgrade-agent", client),
  uninstallPlan: client => ipcRenderer.invoke("onelink:uninstall-plan", client),
  uninstall: input => ipcRenderer.invoke("onelink:uninstall", input),
  preview: (input) => ipcRenderer.invoke("onelink:preview", input),
  apply: (token) => ipcRenderer.invoke("onelink:apply", token),
  restore: (id) => ipcRenderer.invoke("onelink:restore", id),
