function createPlatformLogin({ BrowserWindow, session, platform }) {
  let loginWindow;
  let pending;
  const websiteOrigins = new Set(['https://onelinkai.cloud', 'https://www.onelinkai.cloud']);
  const allowedHosts = new Set(['onelinkai.cloud', 'www.onelinkai.cloud', 'open.weixin.qq.com', 'open.work.weixin.qq.com', 'graph.qq.com', 'github.com', 'accounts.google.com']);
  function allowed(url) { try { const parsed = new URL(url); return parsed.protocol === 'https:' && allowedHosts.has(parsed.hostname); } catch { return false; } }
  async function login(parent) {
    if (pending) { loginWindow?.show(); return pending; }
    pending = new Promise((resolve, reject) => {
      const authSession = session.fromPartition('onelink-login');
      authSession.setPermissionRequestHandler((_contents, _permission, callback) => callback(false));
      authSession.setPermissionCheckHandler(() => false);
      loginWindow = new BrowserWindow({ width: 1000, height: 780, parent, title: '登录 OneLinkAI', webPreferences: {
        session: authSession, nodeIntegration: false, contextIsolation: true, sandbox: true,
      } });
      const window = loginWindow;
      let settled = false;
      let importing = false;
      window.webContents.setWindowOpenHandler(({ url }) => {
        if (allowed(url)) window.loadURL(url).catch(() => {});
        return { action: 'deny' };
      });
      window.webContents.on('will-navigate', (event, url) => { if (!allowed(url)) event.preventDefault(); });
      window.webContents.on('will-redirect', (event, url) => { if (!allowed(url)) event.preventDefault(); });
      window.webContents.on('will-attach-webview', event => event.preventDefault());
      // Observe only token responses generated by this isolated, user-operated login window.
      window.webContents.debugger.attach('1.3');
      const captureReady = window.webContents.debugger.sendCommand('Fetch.enable', {
        patterns: [{ urlPattern: 'https://api.onelinkai.cloud/sso/client/token*', requestStage: 'Response' }],
      });
      window.webContents.debugger.on('message', async (_event, method, params) => {
        if (method !== 'Fetch.requestPaused') return;
        let body;
        let captureError;
        try {
          // Fetch keeps the response available until we resume it, including across navigation.
          const url = new URL(params.request.url);
          const top = new URL(window.webContents.getURL());
          if (!settled && !importing && websiteOrigins.has(top.origin) &&
              url.origin === 'https://api.onelinkai.cloud' && url.pathname === '/sso/client/token' &&
              params.request.method === 'POST' && params.responseStatusCode === 200) {
            importing = true;
            const response = await window.webContents.debugger.sendCommand('Fetch.getResponseBody', { requestId: params.requestId });
            body = JSON.parse(response.base64Encoded ? Buffer.from(response.body, 'base64').toString('utf8') : response.body);
          }
        } catch (error) { captureError = error; }
        finally {
          try {
            await window.webContents.debugger.sendCommand('Fetch.continueRequest', { requestId: params.requestId });
          } catch (error) { captureError ||= error; }
        }
        if (settled) return;
        if (!body && !captureError) return;
        try {
          if (captureError) throw captureError;
          if (body.code !== 200 || !body.data?.access_token) { importing = false; return; }
          const result = await platform.acceptSession({ accessToken: body.data.access_token, refreshToken: body.data.refresh_token });
          settled = true;
          resolve(result);
          window.close();
        } catch (error) {
          settled = true;
          reject(new Error('登录会话接入失败：' + error.message));
          window.close();
        }
      });
      window.on('closed', () => {
        loginWindow = null;
        if (!settled) { settled = true; reject(new Error('已取消登录')); }
      });
      captureReady.then(() => window.loadURL('https://onelinkai.cloud/Login')).catch(() => {
        if (!settled) { settled = true; reject(new Error('官网登录连接失败，请检查网络后重试')); window.close(); }
      });
    }).finally(() => { pending = null; });
    return pending;
  }
  async function logout() {
    loginWindow?.close();
    await platform.logout();
    await session.fromPartition('onelink-login').clearStorageData();
    return platform.status();
  }
  return { login, logout };
}
module.exports = { createPlatformLogin };
